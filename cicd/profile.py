"""Personalized portable CI pipeline profile and renderer."""
import json
from typing import Literal
from pydantic import BaseModel,Field,field_validator
Engine=Literal["github_actions","gitlab_ci","bitbucket_pipelines","gitea_actions","generic_git"]
class CICDProfile(BaseModel):
    engine:Engine="github_actions"
    language:Literal["python","node","go","generic"]="python"
    python_version:str="3.12"
    node_version:str="22"
    go_version:str="1.24"
    install_command:str="pip install -r requirements.txt -r requirements-dev.txt"
    lint_command:str="ruff check . && ruff format --check ."
    test_command:str="pytest --tb=short -q"
    build_command:str|None=None
    security_command:str|None="bandit -r . -x tests -ll"
    branches:list[str]=Field(default_factory=lambda:["main","develop"])
    auto_recovery:bool=True
    publish_recovery_pr:bool=False
    deployment_command:str|None=None
    require_deployment_approval:bool=True
    @field_validator("branches")
    @classmethod
    def valid_branches(cls,v):
        v=list(dict.fromkeys(x.strip() for x in v if x.strip()))
        if not v or len(v)>20 or any(len(x)>100 for x in v):raise ValueError("Configure 1-20 valid branches")
        return v
    @field_validator("install_command","lint_command","test_command","build_command","security_command","deployment_command")
    @classmethod
    def valid_commands(cls,v):
        if v is not None and (len(v)>1000 or "\x00" in v):raise ValueError("Commands must be <=1000 chars and contain no NUL")
        return v.strip() if v else None
def render_pipeline(p:CICDProfile)->dict:
    steps=[p.install_command,p.lint_command]+([p.build_command] if p.build_command else [])+[p.test_command]+([p.security_command] if p.security_command else [])
    steps=[s for s in steps if s]
    if p.engine in ("github_actions","gitea_actions"):
        lines=["name: Nakima CI","on:","  push:","    branches:"]+["      - "+json.dumps(b) for b in p.branches]+["  pull_request:","permissions:","  contents: read","concurrency:","  group: nakima-ci","  cancel-in-progress: true","jobs:","  validate:","    runs-on: ubuntu-latest","    steps:","      - uses: actions/checkout@v4"]
        if p.language=="python":lines+=["      - uses: actions/setup-python@v5","        with:",f"          python-version: {json.dumps(p.python_version)}"]
        elif p.language=="node":lines+=["      - uses: actions/setup-node@v4","        with:",f"          node-version: {json.dumps(p.node_version)}"]
        elif p.language=="go":lines+=["      - uses: actions/setup-go@v5","        with:",f"          go-version: {json.dumps(p.go_version)}"]
        for i,cmd in enumerate(steps):lines += [f"      - name: Stage {i+1}","        run: |"]+["          "+line for line in cmd.splitlines()]
        return {"path":".github/workflows/nakima-ci.yml","content":"\n".join(lines)+"\n"}
    if p.engine=="gitlab_ci":
        lines=["stages:","  - validate","validate:","  stage: validate","  image: python:3.12","  script:"]+["    - "+json.dumps(c) for c in steps]+["  rules:","    - if: '$CI_PIPELINE_SOURCE == \"merge_request_event\"'"]
        lines += ["    - if: '$CI_COMMIT_BRANCH == \""+b+"\"'" for b in p.branches]
        return {"path":".gitlab-ci.yml","content":"\n".join(lines)+"\n"}
    if p.engine=="bitbucket_pipelines":
        lines=["image: atlassian/default-image:4","pipelines:","  branches:"]
        for b in p.branches:lines += ["    "+json.dumps(b)+":","      - step:","          name: Nakima validation","          script:"]+["            - "+json.dumps(c) for c in steps]
        lines += ["  pull-requests:","    '**':","      - step:","          name: Nakima validation","          script:"]+["            - "+json.dumps(c) for c in steps]
        return {"path":"bitbucket-pipelines.yml","content":"\n".join(lines)+"\n"}
    lines=["#!/usr/bin/env bash","set -euo pipefail","# Generated by Nakima."]
    for i,c in enumerate(steps):lines += [f"echo 'Stage {i+1}'",c]
    return {"path":".nakima/ci.sh","content":"\n".join(lines)+"\n"}
